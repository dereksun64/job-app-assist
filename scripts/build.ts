/**
 * Builds what the plugin ships, from src/:
 * - plugin/dist/dashboard.html: the self-contained dashboard page (Artifact page contract:
 *   no doctype, html, head or body tags; title first; everything inlined).
 * - plugin/dist/jaa.mjs: the Node CLI skills run to validate documents.
 *
 * `--check` builds in memory and fails if the committed files are out of date.
 */
import { build } from "esbuild";
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const check = process.argv.includes("--check");

const manifest = JSON.parse(await readFile(`${root}plugin/.claude-plugin/plugin.json`, "utf8")) as {
  version: string;
};

const NOTICE = "Generated by scripts/build.ts from src/. Do not edit by hand.";

async function bundle(options: Parameters<typeof build>[0]): Promise<string> {
  const result = await build({
    bundle: true,
    write: false,
    legalComments: "none",
    logLevel: "warning",
    absWorkingDir: root,
    ...options,
  });
  const [output] = result.outputFiles ?? [];
  if (!output) throw new Error("esbuild produced no output");
  return output.text;
}

async function dashboardPage(): Promise<string> {
  const script = await bundle({
    entryPoints: ["src/dashboard/main.tsx"],
    format: "iife",
    platform: "browser",
    target: "es2022",
    minify: true,
    jsx: "automatic",
    jsxImportSource: "preact",
    define: { __PAGE_VERSION__: JSON.stringify(manifest.version) },
  });
  const css = await readFile(`${root}src/dashboard/styles.css`, "utf8");
  const safeScript = script.replaceAll("</script", "<\\/script");
  return [
    "<title>Job App Assist</title>",
    '<meta name="claude:viewport-fit-sides" content="cover">',
    `<meta name="job-app-assist:page-version" content="${manifest.version}">`,
    `<!-- ${NOTICE} -->`,
    '<link rel="preconnect" href="https://fonts.googleapis.com">',
    '<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>',
    '<link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=Bricolage+Grotesque:opsz,wght@12..96,600..700&family=Instrument+Sans:wght@400..600&display=swap">',
    `<style>\n${css.trim()}\n</style>`,
    '<div id="app"></div>',
    `<script>${safeScript.trim()}</script>`,
    "",
  ].join("\n");
}

async function cli(): Promise<string> {
  return bundle({
    entryPoints: ["src/cli/main.ts"],
    format: "esm",
    platform: "node",
    target: "node20",
    banner: { js: `#!/usr/bin/env node\n// ${NOTICE}` },
  });
}

const outputs: Record<string, string> = {
  "plugin/dist/dashboard.html": await dashboardPage(),
  "plugin/dist/jaa.mjs": await cli(),
};

let stale = false;
for (const [path, text] of Object.entries(outputs)) {
  if (check) {
    const current = await readFile(`${root}${path}`, "utf8").catch(() => "");
    if (current !== text) {
      console.error(`${path} is out of date. Run npm run build and commit the result.`);
      stale = true;
    }
  } else {
    await writeFile(`${root}${path}`, text);
    console.log(`Wrote ${path} (${(text.length / 1024).toFixed(1)} KB)`);
  }
}
if (stale) process.exitCode = 1;
